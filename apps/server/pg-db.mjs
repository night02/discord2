  "CREATE TABLE IF NOT EXISTS direct_messages (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,thread_id TEXT NOT NULL REFERENCES direct_threads(id) ON DELETE CASCADE,author_id TEXT NOT NULL REFERENCES users(id),content TEXT NOT NULL,created_at TEXT NOT NULL)",
  "CREATE INDEX IF NOT EXISTS direct_messages_thread_idx ON direct_messages(thread_id,id)",
  // Nullable keys preserve compatibility with older clients and imported messages.
  "ALTER TABLE messages ADD COLUMN IF NOT EXISTS client_nonce TEXT",
  "ALTER TABLE direct_messages ADD COLUMN IF NOT EXISTS client_nonce TEXT",
  "CREATE UNIQUE INDEX IF NOT EXISTS messages_client_nonce_idx ON messages(channel_id,author_id,client_nonce)",
  "CREATE UNIQUE INDEX IF NOT EXISTS dms_client_nonce_idx ON direct_messages(thread_id,author_id,client_nonce)"
